export function translator(lang: Language) {
  const i = ["id", "en", "ms", "ja", "zh"].indexOf(lang);
  return (key: Key) => rows[key][i] || rows[key][0];
}
export const categoryKey = (id: string): Key => (id === "home" ? "homeCategory" : (id as Key));
export function formatMoney(n: number, currency: Currency, lang: Language) {
  return new Intl.NumberFormat(localeMap[lang], {
    style: "currency",
    currency,
    maximumFractionDigits: currency === "JPY" || currency === "IDR" ? 0 : 2,
  }).format(n);
}
export function formatDate(date: string, lang: Language) {
  return new Date(date + "T12:00:00").toLocaleDateString(localeMap[lang], {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}
